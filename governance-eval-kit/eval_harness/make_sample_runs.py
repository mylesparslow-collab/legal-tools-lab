#!/usr/bin/env python3
"""Generate two made-up tool runs so the scorer can be tried without any AI tool.

These are NOT results from Microsoft 365 Copilot, Claude or any other product.
They are built from the answer keys with a fixed random seed:

  sample_tool_a  finds most defects, quotes exactly, adds an occasional extra finding
  sample_tool_b  finds fewer, sometimes paraphrases inside quotation marks, adds more extras

Usage: python3 make_sample_runs.py
"""
import json
import random
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from harness.corpus import list_doc_ids, load_document  # noqa: E402

OUT = Path(__file__).resolve().parent / "sample_runs"
PROFILES = {
    "sample_tool_a": dict(label="Sample Tool A (made-up output, not a real product)", seed=11,
                          p_high=0.95, p_medium=0.80, p_paraphrase=0.0, extras=(0, 1), minutes=(3, 6)),
    "sample_tool_b": dict(label="Sample Tool B (made-up output, not a real product)", seed=29,
                          p_high=0.62, p_medium=0.45, p_paraphrase=0.25, extras=(1, 3), minutes=(2, 5)),
}


def _paraphrase(q: str) -> str:
    words = q.split()
    return " ".join(words[: max(6, len(words) // 2)]) + " and related obligations as described above"


def _filler_sentences(text: str, taken: list[str]) -> list[str]:
    out = []
    for para in text.split("\n"):
        para = para.strip()
        if 120 <= len(para) <= 380 and not para.startswith(("#", "|", "_", "-", "*")) and "**" not in para:
            if not any(t[:40] in para for t in taken):
                out.append(para)
    return out


def build(name: str) -> dict:
    prof = PROFILES[name]
    rng = random.Random(prof["seed"])
    docs = []
    for doc_id in list_doc_ids():
        doc = load_document(doc_id)
        findings = []
        filler = _filler_sentences(doc.text, [q for d in doc.defects for q in d.quotes])
        for d in doc.defects:
            p = prof["p_high"] if d.severity == "high" else prof["p_medium"]
            if rng.random() > p:
                continue
            # A missing-clause defect has no text to quote; the prompt asks for the nearest clause.
            quote = d.quotes[0] if d.quotes else re.sub(r"\s+", " ", filler.pop(0))[:300]
            if quote and rng.random() < prof["p_paraphrase"]:
                quote = _paraphrase(quote)
            findings.append({"issue": d.why, "authority": d.authority, "quote": quote, "severity": d.severity})
        for _ in range(rng.randint(*prof["extras"])):
            if filler:
                para = filler.pop(rng.randrange(len(filler)))
                findings.append({"issue": "This provision may be one-sided and should be reviewed.",
                                 "authority": "", "quote": re.sub(r"\s+", " ", para)[:300], "severity": "medium"})
        rng.shuffle(findings)
        docs.append({"doc_id": doc_id, "tool_minutes": rng.randint(*prof["minutes"]), "findings": findings})
    return {"tool": prof["label"], "note": "Generated by make_sample_runs.py from the answer keys. Not a benchmark of any product.",
            "documents": docs}


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    for name in PROFILES:
        (OUT / f"{name}.json").write_text(json.dumps(build(name), indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        print("wrote", OUT / f"{name}.json")
